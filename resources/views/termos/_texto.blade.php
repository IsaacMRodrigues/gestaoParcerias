<h2>1. O que são estes Termos</h2>
<p>Estes Termos de Uso regem o acesso e o uso da Plataforma de Gestão de Parcerias (PGP) do Município de São Gonçalo
do Rio Abaixo/MG, o sistema em que a Administração Municipal e as Organizações da Sociedade Civil (OSCs) conduzem as
parcerias regidas pela Lei Federal nº 13.019/2014 e pelo Decreto Municipal nº 048/2020: planejamento, chamamento
público, manifestação de interesse, celebração, execução, alterações e prestação de contas.</p>
<p>Ao marcar "Li e aceito os Termos de Uso", o usuário declara que leu, entendeu e concorda com todas as regras abaixo.
Quem não concordar não deve usar a Plataforma. O aceite fica registrado com a data, a hora, a versão dos Termos e o
endereço IP da conexão.</p>

<h2>2. Quem é quem</h2>
<ul>
    <li><strong>Administração:</strong> o Município de São Gonçalo do Rio Abaixo, por suas Secretarias e pelo Setor de
        Convênios e Parcerias (SCP), que gere a Plataforma.</li>
    <li><strong>Usuário interno:</strong> o servidor ou agente público com conta na Plataforma, lotado em uma
        Secretaria ou setor, que atua nos trâmites conforme os perfis que lhe foram concedidos.</li>
    <li><strong>Usuário da OSC:</strong> o responsável legal da organização e os integrantes da equipe que ele
        cadastra, cada um com as funções que o responsável legal lhe atribuiu.</li>
    <li><strong>Proponente:</strong> qualquer pessoa física ou jurídica que apresenta manifestação de interesse
        social pelo formulário público, com ou sem conta.</li>
</ul>

<h2>3. Cadastro e conta</h2>
<ul>
    <li>Os dados do cadastro devem ser verdadeiros, completos e mantidos atualizados, em especial o nome, o CPF, o
        e-mail e, para as OSCs, os dados da organização e do seu representante legal.</li>
    <li>A conta é pessoal e intransferível. O login e a senha são de uso exclusivo do titular, que deve mantê-los em
        sigilo e não pode emprestá-los, compartilhá-los ou anotá-los onde outros tenham acesso.</li>
    <li>A conta de servidor só passa a funcionar depois de conferida e aprovada pela Administração. A conta da OSC e
        as contas da sua equipe podem ser conferidas a qualquer tempo.</li>
    <li>O responsável legal da OSC responde pela organização na Plataforma e pelas contas que cadastrar para a sua
        equipe, e deve desativá-las quando a pessoa deixar de atuar pela organização.</li>
    <li>Suspeita de uso indevido da conta, perda ou vazamento da senha deve ser comunicada de imediato pelo Suporte
        da Plataforma.</li>
    <li>A Administração pode suspender ou desativar a conta usada em desacordo com estes Termos ou com a lei, e a
        conta de quem deixou de ter vínculo que justifique o acesso.</li>
</ul>

<h2>4. Assinatura eletrônica</h2>
<ul>
    <li>Os documentos da Plataforma são assinados eletronicamente, com a confirmação da senha pessoal no ato, nos
        termos da Lei Federal nº 14.063/2020 e da regulamentação municipal.</li>
    <li>A assinatura é ato pessoal. A assinatura feita com as credenciais do usuário presume-se feita por ele, que
        responde pelo conteúdo que assinou.</li>
    <li>Cada assinatura registra o nome e o cargo do signatário, a data e a hora oficiais de Brasília, o código de
        integridade do texto assinado, o endereço IP e o navegador usados, numa trilha de auditoria que não pode ser
        alterada.</li>
    <li>Todo documento assinado traz código de validação e QR Code, e qualquer pessoa pode conferir a sua
        autenticidade e integridade na página pública de validação.</li>
    <li>Depois de assinado, o documento não pode mais ser editado. A correção se faz por devolução, que anula a
        assinatura (o registro dela permanece na trilha) e exige nova assinatura.</li>
</ul>

<h2>5. Responsabilidades do usuário</h2>
<ul>
    <li>Usar a Plataforma só para as finalidades públicas a que ela se destina e dentro das atribuições do seu
        perfil.</li>
    <li>Responder pela veracidade das informações que prestar e pela autenticidade dos documentos que anexar.
        Informação falsa ou documento adulterado sujeita o responsável às sanções administrativas, civis e penais
        cabíveis, além das previstas na Lei nº 13.019/2014 e no edital.</li>
    <li>Acompanhar os trâmites, os prazos e as comunicações das parcerias de que participa.</li>
    <li>Guardar sigilo sobre informações não públicas a que tiver acesso em razão do seu perfil, como documentos
        internos da Administração e dados pessoais de terceiros.</li>
</ul>
<p>É proibido, entre outras condutas: acessar ou tentar acessar dados, contas ou funções sem autorização; contornar
controles de acesso, de assinatura ou de segurança; enviar arquivo com vírus ou código malicioso; usar robôs ou
acessos automatizados não autorizados; e usar a Plataforma para fins particulares, comerciais ou ilícitos.</p>

<h2>6. Comunicações</h2>
<ul>
    <li>O e-mail cadastrado é o canal pelo qual a Plataforma envia avisos: a vez de agir em um trâmite, decisões,
        devoluções, prazos e respostas do Suporte. Cabe ao usuário mantê-lo correto e acompanhá-lo, inclusive a caixa
        de spam.</li>
    <li>Os avisos por e-mail ajudam, mas não substituem as publicações oficiais nem os prazos fixados em lei, no
        edital ou no termo de parceria, que valem por si.</li>
</ul>

<h2>7. Transparência</h2>
<p>As parcerias com OSCs são públicas por força da Lei nº 13.019/2014 e da Lei Federal nº 12.527/2011 (Lei de Acesso à
Informação). Por isso, são divulgados no Portal Público, entre outros: os chamamentos e os seus resultados, as
parcerias celebradas, com valores, objeto e vigência, os repasses e as prestações de contas, e as manifestações de
interesse social recebidas, sem o e-mail do proponente. A OSC e o proponente declaram ciência dessa publicidade.</p>

<h2>8. Dados pessoais</h2>
<ul>
    <li>A Administração trata dados pessoais na Plataforma nos termos da Lei Federal nº 13.709/2018 (Lei Geral de
        Proteção de Dados Pessoais), para executar políticas públicas e cumprir obrigações legais e regulatórias
        (arts. 7º, II e III, e 23).</li>
    <li>São tratados os dados de identificação e contato (nome, CPF, RG do representante da OSC, e-mail, telefone,
        matrícula e lotação), os registros de acesso e de operações e os registros de assinatura descritos no item
        4, além dos dados pessoais que constem dos documentos anexados pelos usuários.</li>
    <li>Os dados servem para identificar os usuários, controlar o acesso, conduzir e registrar os trâmites,
        comprovar a autoria das assinaturas, prestar contas aos órgãos de controle e dar a publicidade exigida em lei.
        Não são usados para outra finalidade nem vendidos ou cedidos a particulares.</li>
    <li>Os dados podem ser compartilhados com os órgãos de controle e fiscalização, como o Tribunal de Contas do
        Estado de Minas Gerais, a controladoria do Município e o Ministério Público, quando a lei exigir ou eles
        requisitarem.</li>
    <li>Os dados e documentos são guardados pelo prazo que a legislação e as normas de arquivo público exigem,
        inclusive depois do fim da parceria ou da desativação da conta.</li>
    <li>O titular pode exercer os direitos do art. 18 da Lei nº 13.709/2018, como confirmar o tratamento, acessar e
        corrigir os seus dados, pelos canais oficiais do Município ou pelo Suporte da Plataforma, observados os limites
        das obrigações legais de guarda e de publicidade.</li>
</ul>

<h2>9. Registros e segurança</h2>
<p>A Plataforma registra os acessos e as operações feitas por cada conta, com data, hora e endereço IP, para
segurança, auditoria e apuração de responsabilidades. Esses registros podem ser usados como prova em processos
administrativos e judiciais.</p>

<h2>10. Disponibilidade</h2>
<p>A Administração busca manter a Plataforma disponível de forma contínua, mas ela pode ficar fora do ar para
manutenção ou por falha técnica. A indisponibilidade que impeça o cumprimento de um prazo deve ser comunicada pelo
Suporte assim que ocorrer, e será tratada pela Administração conforme o edital e a legislação aplicável.</p>

<h2>11. Documentos e conteúdo</h2>
<p>A Plataforma, os seus modelos de documento e o seu código pertencem ao Município. Ao anexar um documento, o
usuário declara ter o direito de usá-lo e autoriza o seu uso pela Administração para os fins da parceria e da
publicidade legal.</p>

<h2>12. Descumprimento</h2>
<p>O descumprimento destes Termos pode levar à suspensão ou ao bloqueio do acesso, sem prejuízo da apuração de
responsabilidade administrativa, civil e penal, e das consequências previstas na Lei nº 13.019/2014, no edital e no
termo de parceria.</p>

<h2>13. Mudanças nos Termos</h2>
<p>Estes Termos podem ser atualizados. Cada versão tem número e data. Quando houver nova versão, a Plataforma pedirá
um novo aceite no acesso seguinte, e o uso só continua com ele.</p>

<h2>14. Suporte e foro</h2>
<p>Dúvidas, problemas e pedidos sobre a Plataforma e estes Termos são tratados pelo Suporte, disponível no menu do
sistema. Fica eleito o foro da comarca a que pertence o Município de São Gonçalo do Rio Abaixo/MG para as questões
decorrentes destes Termos.</p>
